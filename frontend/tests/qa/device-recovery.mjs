const fs = await import('node:fs/promises')
const assert = (await import('node:assert/strict')).default
const root = '/tmp/readflix-route-theme-qa'
const fixtures = JSON.parse(await fs.readFile(`${root}/fixtures.json`, 'utf8'))
const task = await taskSpace(29), page = task.page('p1')
const p2 = await task.newPage()
console.log({secondaryPage:p2.label})
const base = 'http://127.0.0.1:5173', epub=fixtures.books[0].id, txt=fixtures.books[3].id
const results=[]
async function pass(name, data={}) { results.push({name,...data}); await fs.writeFile(`${root}/device-results.json`,JSON.stringify(results,null,2)); console.log('PASS '+name) }
await p2.goto(`${base}/reader/${epub}?panel=contents`)
await p2.waitForSelector('[aria-label="選擇讀者 閱讀測試"]')
assert.match(await p2.url(),/returnTo=/)
await p2.click('[aria-label="選擇讀者 閱讀測試"]')
await p2.waitForURL('**panel=contents')
await p2.waitForSelector('[aria-label="關閉目錄"]')
await pass('fresh tab reader gate preserves requested contents URL')
await p2.goto(`${base}/settings`); await p2.waitForSelector('[aria-label="畫面外觀"]')
await p2.click('text="深色"')
await page.waitForFunction(() => document.documentElement.dataset.theme==='dark')
await pass('same browser tabs receive appearance storage updates')
// Bootstrap still sets background even when the React entry is blocked.
await p2.cdp('Network.enable',{})
await p2.cdp('Network.setBlockedURLs',{urls:[`${base}/src/main.tsx`]})
await p2.reload()
const firstPaint=await p2.evaluate(() => ({theme:document.documentElement.dataset.theme,bg:getComputedStyle(document.documentElement).backgroundColor,rootEmpty:!document.getElementById('root').childElementCount}))
assert.equal(firstPaint.theme,'dark'); assert.equal(firstPaint.bg,'rgb(24, 26, 25)'); assert.equal(firstPaint.rootEmpty,true)
await pass('dark first paint before React bundle',firstPaint)
await p2.cdp('Network.setBlockedURLs',{urls:[]}); await p2.reload(); await p2.waitForSelector('[aria-label="畫面外觀"]')
await p2.click('text="跟隨系統"')
await p2.cdp('Emulation.setEmulatedMedia',{features:[{name:'prefers-color-scheme',value:'light'},{name:'prefers-reduced-motion',value:'reduce'}]})
await p2.waitForFunction(() => document.documentElement.dataset.theme==='light')
await p2.cdp('Emulation.setEmulatedMedia',{features:[{name:'prefers-color-scheme',value:'dark'},{name:'prefers-reduced-motion',value:'reduce'}]})
await p2.waitForFunction(() => document.documentElement.dataset.theme==='dark')
await p2.click('text="淺色"')
await p2.cdp('Emulation.setEmulatedMedia',{features:[{name:'prefers-color-scheme',value:'dark'},{name:'prefers-reduced-motion',value:'reduce'}]})
assert.equal(await p2.evaluate(() => document.documentElement.dataset.theme),'light')
await pass('system appearance responds to OS; explicit light overrides dark OS')
const layoutSnapshot=await p2.evaluate(() => ({inputFont:getComputedStyle(document.querySelector('input')).fontSize,transition:getComputedStyle(document.querySelector('button')).transitionDuration}))
assert.equal(layoutSnapshot.inputFont,'16px'); assert.ok(layoutSnapshot.transition.includes('e-05') || layoutSnapshot.transition.includes('0.00001'))
await pass('16px inputs and reduced-motion CSS',layoutSnapshot)
// Block only this QA page's storage access to exercise the guarded bootstrap and theme store.
const injected=await p2.cdp('Page.addScriptToEvaluateOnNewDocument',{source:"Storage.prototype.getItem = function(){throw new DOMException('QA storage denial','SecurityError')}; Storage.prototype.setItem = function(){throw new DOMException('QA storage denial','SecurityError')};"})
await p2.goto(`${base}/`); await p2.waitForSelector('[aria-label="選擇讀者 閱讀測試"]')
await p2.click('[aria-label="切換為淺色模式"]'); assert.equal(await p2.evaluate(() => document.documentElement.dataset.theme),'light')
await pass('storage-denied browser can load and toggle appearance')
await p2.cdp('Page.removeScriptToEvaluateOnNewDocument',{identifier:injected.identifier}); await p2.reload()
await p2.waitForSelector('[aria-label="選擇讀者 閱讀測試"]')
await p2.evaluate(() => sessionStorage.setItem('readflix.reader','qa-deleted-reader'))
await p2.goto(`${base}/library`); await p2.waitForSelector('[aria-label="選擇讀者 閱讀測試"]')
assert.match(await p2.url(),/returnTo=/)
await pass('deleted/stale reader ID returns to selection')
await p2.click('[aria-label="選擇讀者 另一位讀者"]'); await p2.waitForURL('**/library')
await p2.goto(`${base}/reader/${txt}`); await p2.waitForFunction(() => document.querySelector('.epub-reader-root')?.innerText.includes('本機合成測試資料'))
assert.equal(await p2.evaluate(() => document.querySelector('input[type="range"]')?.value),'0')
await pass('second reader does not inherit first reader TXT progress')
await page.goto(`${base}/reader/${txt}`); await page.waitForFunction(() => document.querySelector('.epub-reader-root')?.innerText.includes('本機合成測試資料'))
await page.evaluate(() => { const original=window.fetch; window.fetch=(input,init)=>String(input).endsWith('/progress')&&init?.method==='PUT'?Promise.reject(new Error('QA offline progress')):original(input,init) })
await page.focus('input[type="range"]'); await page.press('input[type="range"]','ArrowRight'); await page.press('input[type="range"]','ArrowRight')
await page.waitForFunction(() => document.body.innerText.includes('進度暫存於本機'))
const offline=await page.evaluate(({user,book})=>JSON.parse(localStorage.getItem(`readflix.progress.${user}.${book}`)),{user:fixtures.users[0].id,book:txt})
assert.ok(offline?.pending)
await page.reload(); await page.waitForFunction(() => document.querySelector('.epub-reader-root')?.innerText.includes('本機合成測試資料'))
await page.waitForFunction(expected => Math.abs(Number(document.querySelector('input[type="range"]')?.value)-expected)<=1, Number(offline.cfi.split('@@')[1])*100)
const restored=Number(await page.evaluate(() => document.querySelector('input[type="range"]')?.value))
assert.ok(Math.abs(restored-Number(offline.cfi.split('@@')[1])*100)<=1)
await pass('offline progress recovery survives refresh',{restored})
// Layout changes still save without a theme key, and keyboard controls do not turn book pages.
await page.click('[aria-label="閱讀設定"]'); await page.waitForSelector('[aria-label="關閉閱讀設定"]')
await page.evaluate(() => { const original=window.fetch; window.__qaSettings=[]; window.fetch=(input,init)=>{if(String(input).endsWith('/settings')&&init?.method==='PUT')window.__qaSettings.push(JSON.parse(init.body));return original(input,init)} })
await page.focus('input[aria-label="字體大小"]'); await page.press('input[aria-label="字體大小"]','ArrowRight')
await page.waitForFunction(() => window.__qaSettings.length>0)
const saved=await page.evaluate(() => window.__qaSettings)
assert.ok(saved.every(body=>!('theme' in body)))
await pass('reader layout API payload excludes device appearance',{saved})
for(const mode of ['light','dark']) {
  await page.click(`text="${mode==='light'?'淺色':'深色'}"`)
  for(const width of [768,1024]) {
    await page.cdp('Emulation.setDeviceMetricsOverride',{width,height:900,deviceScaleFactor:1,mobile:false})
    await page.screenshot({path:`${root}/reader-settings-${mode}-${width}.png`})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    await pass(`reader settings ${mode} ${width}`)
  }
}
await page.goto(`${base}/library?view=reading`); await page.waitForSelector('[aria-label="閱讀 山間的日常"]')
await page.focus('[aria-label="閱讀 山間的日常"]'); await page.press('[aria-label="閱讀 山間的日常"]','Enter'); await page.waitForSelector('foliate-paginator')
await pass('book card is a keyboard-operable real reader link')
console.log(JSON.stringify({passed:results.length,report:`${root}/device-results.json`}))
